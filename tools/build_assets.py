# Converts img-src/<key>.(jpg|png|webp) -> img/<key>.webp (640px wide, <80KB),
# regenerates library.js (webp if present, else svg) and sw.js (file list + content-hash cache version).
import os,glob,json,hashlib,re
from PIL import Image
R=os.path.abspath(os.path.join(os.path.dirname(__file__),'..'))
for f in glob.glob(R+'/img-src/*'):
    key=os.path.splitext(os.path.basename(f))[0];out=f'{R}/img/{key}.webp'
    if os.path.exists(out) and os.path.getmtime(out)>os.path.getmtime(f):continue
    im=Image.open(f).convert('RGB');w=640;im=im.resize((w,round(im.height*w/im.width)),Image.LANCZOS)
    for q in (82,75,68,60,52,45):
        im.save(out,'WEBP',quality=q,method=6)
        if os.path.getsize(out)<80_000:break
    print(key,os.path.getsize(out)//1024,'KB q',q)
src=open(R+'/library.js').read();lib=json.loads(re.search(r'const LIBRARY=(\[.*\]);',src,re.S).group(1))
for e in lib:
    e['img']=f"img/{e['key']}.webp" if os.path.exists(f"{R}/img/{e['key']}.webp") else f"img/{e['key']}.svg"
open(R+'/library.js','w').write('// generated by tools/gen_img.py + tools/build_assets.py\nconst LIBRARY='+json.dumps(lib,ensure_ascii=False)+';\n')
core=['index.html','style.css','app.js','journal.js','library.js','manifest.webmanifest','icon-192.png','icon-512.png']
F=['./']+core+[e['img'] for e in lib]
h=hashlib.sha1(b''.join(open(f'{R}/{x}','rb').read() for x in F[1:])).hexdigest()[:8]
import datetime
ver=f"{datetime.date.today():%Y.%m.%d}-{h}"
open(R+'/library.js','a').write(f"const APP_VERSION='{ver}';\n")
sw=f"""// version {ver}
const C='gym-{h}',MARK='gym-upd-protocol',F={json.dumps(F)};
self.addEventListener('install',e=>{{e.waitUntil((async()=>{{const c=await caches.open(C);await Promise.all(F.map(u=>fetch(u,{{cache:'reload'}}).then(r=>{{if(!r.ok)throw new Error(u);return c.put(u,r)}})));
  if(!(await caches.has(MARK)))self.skipWaiting();}})())}});
self.addEventListener('message',e=>{{if(e.data&&e.data.type==='SKIP_WAITING')self.skipWaiting()}});
self.addEventListener('activate',e=>{{e.waitUntil((async()=>{{await caches.open(MARK);for(const k of await caches.keys())if(k!==C&&k!==MARK)await caches.delete(k);await self.clients.claim()}})())}});
self.addEventListener('fetch',e=>{{const q=e.request;if(q.method!=='GET'||new URL(q.url).origin!==location.origin)return;
  e.respondWith(fetch(q,{{cache:'no-cache'}}).then(r=>{{if(r.ok){{const c=r.clone();caches.open(C).then(x=>x.put(q,c))}}return r}}).catch(()=>caches.match(q,{{ignoreSearch:true}}).then(r=>r||caches.match('./'))))}});
"""
open(R+'/sw.js','w').write(sw);assert os.path.getsize(R+'/sw.js')>500
print('sw',ver,len(F),'files; webp:',sum(e['img'].endswith('webp') for e in lib),'/',len(lib))
